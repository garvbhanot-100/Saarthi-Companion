export const translationsWithHome: Record<
  LanguageCode,
  TranslationDictionary
> = Object.fromEntries(
  Object.entries(translations).map(([language, dictionary]) => [
    language,
    {
      ...dictionary,
      ...homeTranslations[language as LanguageCode],
    },
  ]),
) as Record<LanguageCode, TranslationDictionary>;

export function getHomeTranslation(
  language: LanguageCode,
  key: TranslationKey,
): string | undefined {
  const translatedValue =
    homeTranslations[language]?.[key] ?? translations[language][key];

  if (
    language !== "en" &&
    translatedValue === translations.en[key]
  ) {
    return undefined;
  }

  return translatedValue;
}

export function getMissingHomeSearchTranslations(
  language: LanguageCode
): TranslationKey[] {
  return homeSearchKeys.filter((key) => {
    const translatedValue = getHomeTranslation(language, key);

    return (
      typeof translatedValue !== "string" ||
      translatedValue.trim() === ""
    );
  });
}